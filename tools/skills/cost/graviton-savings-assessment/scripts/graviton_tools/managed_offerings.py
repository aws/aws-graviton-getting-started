"""Real instance-class availability for managed services (RDS / ElastiCache).

Why this exists
---------------
Graviton targets are generated by *string construction*
(``instance_classifier._build_graviton_family``), not by asking AWS what exists.
For plain EC2, ``instance_offerings`` validates candidates against
DescribeInstanceTypeOfferings. But that API does not enumerate the ``db.``/
``cache.`` classes used by RDS and ElastiCache, so without this module those
families have no availability check beyond "did the Pricing API return a price".

That gap produces phantom recommendations. Example: ``db.r6i.32xlarge``
(Aurora MySQL) generates a ``db.r7g.32xlarge`` target, but RDS r7g caps at
16xlarge — no db.r7g.32xlarge exists, so the row would get no price and the
report would display a size AWS does not sell.

This module resolves the real orderable classes so callers can:
  1. drop candidate sizes AWS does not actually offer, and
  2. find the nearest-smaller *real* size for a capacity-adjusted suggestion.

Failure posture
---------------
Advisory, matching ``instance_offerings``. Any API failure (missing IAM,
throttling, unknown region/engine) yields ``None`` — "unknown, do not filter" —
never an empty set, which would wrongly invalidate every managed target.
Callers MUST treat ``None`` as "skip validation".

IAM (optional; missing perms degrade gracefully to price-only validation):
  rds:DescribeOrderableDBInstanceOptions
  rds:DescribeDBEngineVersions  (version pinning for the options query)
  elasticache:DescribeReservedCacheNodesOfferings
"""
import logging
from typing import Dict, Optional, Set

from .aws_config import bounded_client_config

logger = logging.getLogger(__name__)

# (region, engine) -> set of offered "db.<family>.<size>" (or None if lookup failed).
_rds_cache: Dict[tuple, Optional[Set[str]]] = {}
# region -> set of offered "cache.<family>.<size>" (or None if lookup failed).
_elasticache_cache: Dict[str, Optional[Set[str]]] = {}


def _normalize_rds_engine(display: str) -> Optional[str]:
    """Map a Cost Explorer / display engine name to an RDS API Engine key.

    CE reports engines as "Aurora MySQL", "PostgreSQL", "MariaDB", etc.; the
    RDS API wants "aurora-mysql", "postgres", "mariadb". Returns None for
    engines with no Graviton path (Oracle, SQL Server, Db2) or when
    unrecognized — the caller then skips the orderable-options lookup for that
    row.
    """
    if not display:
        return None
    d = display.strip().lower()
    # Commercial engines have no Graviton offering; don't waste a call.
    if "oracle" in d or "sql server" in d or "sqlserver" in d or "db2" in d:
        return None
    # Explicit, ordered mapping (longest/most-specific first).
    table = [
        ("aurora postgresql", "aurora-postgresql"),
        ("aurora mysql", "aurora-mysql"),
        ("aurora", "aurora-mysql"),  # bare "Aurora" ≈ legacy MySQL-compatible
        ("postgresql", "postgres"),
        ("postgres", "postgres"),
        ("mariadb", "mariadb"),
        ("mysql", "mysql"),
    ]
    for needle, api_key in table:
        if needle in d:
            return api_key
    return None


# How many recent major versions to union when enumerating orderable classes.
# One would do for the class list itself; three is cheap insurance against a
# just-released version that has not yet picked up a Graviton family.
_ORDERABLE_MAJORS = 3


def _version_key(version: str):
    """Sort key by numeric component, so "10.2" ranks above "9.6".

    Plain string ordering gets this wrong, and Aurora spells versions like
    "8.4.mysql_aurora.8.4.8", so non-numeric parts sort last rather than raise.
    """
    return [int(p) if p.isdigit() else -1 for p in version.split(".")]


def _recent_engine_versions(client, engine: str):
    """Newest version of each of the last `_ORDERABLE_MAJORS` major versions.

    Returns [] when the versions cannot be listed, which the caller reads as
    "query unpinned".

    Why pin at all: DescribeOrderableDBInstanceOptions returns a row per
    (engine version x instance class x AZ set), and we keep only
    DBInstanceClass. Leaving the version unpinned pages the entire version
    dimension to throw it away — postgres has 47 versions in us-west-2, and that
    single call took 270s of a 937s run. Pinning returns the same class set in
    seconds (measured: postgres 251 classes and 95 Graviton classes either way).

    Why a union rather than just the newest: a brand-new version can offer fewer
    classes than its predecessors. Measured on aurora-postgresql, the newest
    version omits the six db.r4 sizes that the unpinned call reports. Those are
    deprecated Intel and this set exists to validate *Graviton* targets, so
    losing them is harmless — but the same mechanism could drop a Graviton family
    on the day a version ships, which would silently reject a valid target. Three
    majors costs a few seconds and removes that failure mode.
    """
    try:
        versions = [
            v["EngineVersion"]
            for page in client.get_paginator("describe_db_engine_versions").paginate(Engine=engine)
            for v in page.get("DBEngineVersions", [])
            if v.get("EngineVersion")
        ]
    except Exception as e:
        logger.debug("Could not list %s engine versions (%s); querying orderable "
                     "options unpinned.", engine, type(e).__name__)
        return []

    newest_per_major: Dict[int, str] = {}
    for v in versions:
        major = _version_key(v)[0]
        if major not in newest_per_major or _version_key(v) > _version_key(newest_per_major[major]):
            newest_per_major[major] = v
    return [newest_per_major[m]
            for m in sorted(newest_per_major, reverse=True)[:_ORDERABLE_MAJORS]]


def get_rds_offered_classes(region: str, engine_display: str) -> Optional[Set[str]]:
    """Return the set of orderable ``db.<family>.<size>`` classes for an engine.

    ``engine_display`` is the CE/display engine name (e.g. "Aurora MySQL").
    Returns None when availability could not be determined (unknown engine,
    missing IAM, throttling) — callers must then skip validation.
    """
    engine = _normalize_rds_engine(engine_display)
    if engine is None:
        return None

    key = (region, engine)
    if key in _rds_cache:
        return _rds_cache[key]

    try:
        import boto3
    except ImportError:
        _rds_cache[key] = None
        return None

    try:
        client = boto3.client("rds", region_name=region, config=bounded_client_config())
        offered: Set[str] = set()
        paginator = client.get_paginator("describe_orderable_db_instance_options")
        # One query per pinned version, unioned; falls back to a single unpinned
        # query (slow but complete) when the versions could not be listed.
        version_filters = [{"EngineVersion": v} for v in _recent_engine_versions(client, engine)] or [{}]
        failed = 0
        for extra in version_filters:
            try:
                # 1000 is the API's maximum page size; the default 100 made a
                # large engine's unpinned query take ten times the calls.
                for page in paginator.paginate(Engine=engine, MaxRecords=1000, **extra):
                    for opt in page.get("OrderableDBInstanceOptions", []):
                        cls = opt.get("DBInstanceClass", "")
                        if cls:
                            offered.add(cls.lower())
            except Exception as e:
                # A single version being unorderable in this region is normal and
                # not fatal — the other versions still contribute. Only a total
                # failure falls through to the outer handler.
                failed += 1
                logger.debug("Orderable options unavailable for %s/%s %s (%s).",
                             region, engine, extra or "unpinned", type(e).__name__)
        if failed and version_filters == [{}]:
            # The single unpinned query failed part way: the pages read so far
            # are not the full class list, and caching them as if they were
            # would reject real classes. Treat availability as unknown.
            logger.warning("Orderable options for %s/%s were only partly read; "
                           "availability treated as unknown.", region, engine)
            _rds_cache[key] = None
            return None

        if not offered:
            logger.warning(
                "DescribeOrderableDBInstanceOptions returned no classes for "
                "%s/%s — treating availability as unknown (no filtering).",
                region, engine,
            )
            _rds_cache[key] = None
            return None

        logger.info(
            "RDS orderable classes for %s/%s: %d classes", region, engine, len(offered)
        )
        _rds_cache[key] = offered
        return offered

    except Exception as e:
        logger.warning(
            "Could not verify RDS class availability in %s/%s (%s: %s). Falling "
            "back to price-only validation; phantom sizes may not be flagged. "
            "Grant rds:DescribeOrderableDBInstanceOptions for accurate targeting.",
            region, engine, type(e).__name__, e,
        )
        _rds_cache[key] = None
        return None


def get_elasticache_offered_classes(region: str) -> Optional[Set[str]]:
    """Return the set of ``cache.<family>.<size>`` node types offered in ``region``.

    ElastiCache node types are engine-agnostic for availability purposes, so a
    single per-region lookup suffices. Returns None on any lookup failure.
    """
    if region in _elasticache_cache:
        return _elasticache_cache[region]

    try:
        import boto3
    except ImportError:
        _elasticache_cache[region] = None
        return None

    try:
        client = boto3.client("elasticache", region_name=region, config=bounded_client_config())
        offered: Set[str] = set()
        # Reserved-node offerings enumerate the full node-type catalog per region
        # without needing an engine or an existing cluster.
        paginator = client.get_paginator("describe_reserved_cache_nodes_offerings")
        for page in paginator.paginate():
            for off in page.get("ReservedCacheNodesOfferings", []):
                node = off.get("CacheNodeType", "")
                if node:
                    offered.add(node.lower())

        if not offered:
            logger.warning(
                "DescribeReservedCacheNodesOfferings returned no node types for "
                "%s — treating availability as unknown (no filtering).",
                region,
            )
            _elasticache_cache[region] = None
            return None

        logger.info(
            "ElastiCache node types for %s: %d types", region, len(offered)
        )
        _elasticache_cache[region] = offered
        return offered

    except Exception as e:
        logger.warning(
            "Could not verify ElastiCache node availability in %s (%s: %s). "
            "Falling back to price-only validation. Grant "
            "elasticache:DescribeReservedCacheNodesOfferings for accurate targeting.",
            region, type(e).__name__, e,
        )
        _elasticache_cache[region] = None
        return None
