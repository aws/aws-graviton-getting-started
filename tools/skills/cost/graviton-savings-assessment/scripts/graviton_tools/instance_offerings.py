"""Region-level instance type availability via DescribeInstanceTypeOfferings.

Why this exists
---------------
Graviton targets are generated by *string construction*
(``instance_classifier._build_graviton_family``), not by asking AWS what exists.
That means a fleet can produce candidate types that are not offered in the
customer's region — newly launched families (Graviton5 c9g/m9g) roll out
region by region, and irregular families never had some variants at all.

Without it the only signal is "the Pricing API returned no price", which
conflates three very different situations:

  1. the type genuinely does not exist in this region,
  2. the type exists but pricing lookup failed (missing ``pricing:GetProducts``),
  3. the type exists and is simply free/unpriced in the response shape.

This module resolves (1) directly so callers can stop guessing.

Failure posture
---------------
This is an *advisory* check. If the API call fails for any reason (missing
``ec2:DescribeInstanceTypeOfferings``, throttling, an unknown region), we return
``None`` — meaning "unknown, do not filter" — rather than an empty set, which
would wrongly invalidate every target. Callers must treat ``None`` as
"skip validation", never as "nothing is available".

Only EC2 is covered. RDS/ElastiCache/OpenSearch use ``db.``/``cache.`` types
that this API does not enumerate; those keep price-only validation.
"""
import logging
from typing import Dict, Optional, Set

logger = logging.getLogger(__name__)

# region -> set of offered EC2 instance types (or None if the lookup failed).
# Module-level so a multi-region assessment pays one call per region per session.
_offerings_cache: Dict[str, Optional[Set[str]]] = {}


def get_offered_types(region: str) -> Optional[Set[str]]:
    """Return the set of EC2 instance types offered in ``region``.

    Returns None if availability could not be determined — callers must then
    skip validation rather than treat the result as "none available".
    """
    if region in _offerings_cache:
        return _offerings_cache[region]

    try:
        import boto3
    except ImportError:
        _offerings_cache[region] = None
        return None

    try:
        client = boto3.client("ec2", region_name=region)
        offered: Set[str] = set()
        paginator = client.get_paginator("describe_instance_type_offerings")
        for page in paginator.paginate(
            LocationType="region",
            Filters=[{"Name": "location", "Values": [region]}],
        ):
            for offering in page.get("InstanceTypeOfferings", []):
                itype = offering.get("InstanceType", "")
                if itype:
                    offered.add(itype.lower())

        if not offered:
            # A successful call that returns nothing is not credible for a real
            # region; treat it as unknown so we do not filter everything out.
            logger.warning(
                "DescribeInstanceTypeOfferings returned no types for %s — "
                "treating availability as unknown (no filtering applied).",
                region,
            )
            _offerings_cache[region] = None
            return None

        logger.info("Instance offerings for %s: %d types available", region, len(offered))
        _offerings_cache[region] = offered
        return offered

    except Exception as e:
        # Most commonly AccessDenied on ec2:DescribeInstanceTypeOfferings.
        logger.warning(
            "Could not verify instance availability in %s (%s: %s). Falling back to "
            "price-only validation; unlaunched targets may not be flagged. Grant "
            "ec2:DescribeInstanceTypeOfferings for region-accurate targeting.",
            region, type(e).__name__, e,
        )
        _offerings_cache[region] = None
        return None
